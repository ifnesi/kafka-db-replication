"""
Regenerates everything derived from schema_spec.py (run from the repo root):

    python3 data-generator/gen_artifacts.py

Outputs:
    postgres-init/schema.sql        destination DDL (PostgreSQL)
    db2-init/schema.sql             destination DDL (IBM Db2, lowercase quoted identifiers)
    connectors/*.json               source + 2 sink connector configs
    README.md                       table / primary-key overview (between TABLES markers)
"""

import json
import os

from schema_spec import TABLES, ddl

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
names = [t.name for t in TABLES]


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    print("wrote", rel)


# ---- DDL ------------------------------------------------------------------- #
write("postgres-init/schema.sql",
      "-- GENERATED by data-generator/gen_artifacts.py - do not edit\n\n" +
      ";\n\n".join(ddl(t, "postgres") for t in TABLES) + ";\n")

write("db2-init/schema.sql",
      "-- GENERATED by data-generator/gen_artifacts.py - do not edit\n"
      "CONNECT TO demo;\n\n" +
      ";\n\n".join(ddl(t, "db2") for t in TABLES) + ";\n\nCOMMIT;\nCONNECT RESET;\n")

# ---- Connectors -------------------------------------------------------------- #
AVRO = {
    "key.converter": "io.confluent.connect.avro.AvroConverter",
    "key.converter.schema.registry.url": "http://schema-registry:8081",
    "value.converter": "io.confluent.connect.avro.AvroConverter",
    "value.converter.schema.registry.url": "http://schema-registry:8081",
}

source = {
    "name": "mssql-cdc-source",
    "config": {
        "connector.class": "io.debezium.connector.sqlserver.SqlServerConnector",
        "tasks.max": "1",
        "database.hostname": "mssql",
        "database.port": "1433",
        "database.user": "sa",
        "database.password": "Password!123",
        "database.names": "demo_db",
        "database.encrypt": "false",
        "database.trustServerCertificate": "true",
        "topic.prefix": "mssql",
        "table.include.list": ",".join(f"dbo.{n}" for n in names),
        "snapshot.mode": "initial",
        "schema.history.internal.kafka.bootstrap.servers": "broker:29092",
        "schema.history.internal.kafka.topic": "mssql.schema-history",
        "include.schema.changes": "false",
        # Connect-native types so the JDBC sinks get plain TIMESTAMP/DATE/DECIMAL
        "time.precision.mode": "connect",
        "decimal.handling.mode": "precise",
        # emit a tombstone after each delete event
        "tombstones.on.delete": "true",
        **AVRO,
        # "after state only": unwrap the Debezium envelope, drop the delete event
        # but keep the tombstone (key + null value) so sinks can DELETE the row
        "transforms": "unwrap,route",
        "transforms.unwrap.type": "io.debezium.transforms.ExtractNewRecordState",
        "transforms.unwrap.drop.tombstones": "false",
        "transforms.unwrap.delete.handling.mode": "drop",
        # mssql.demo_db.dbo.customers -> customers
        "transforms.route.type": "org.apache.kafka.connect.transforms.RegexRouter",
        "transforms.route.regex": "mssql\\.demo_db\\.dbo\\.(.*)",
        "transforms.route.replacement": "$1",
        # compacted topics: the latest record per key is always retained
        "topic.creation.default.partitions": "1",
        "topic.creation.default.replication.factor": "1",
        "topic.creation.default.cleanup.policy": "compact",
    },
}


def sink(name, url, user, password):
    return {
        "name": name,
        "config": {
            "connector.class": "io.confluent.connect.jdbc.JdbcSinkConnector",
            "tasks.max": "2",
            "topics": ",".join(names),
            "connection.url": url,
            "connection.user": user,
            "connection.password": password,
            **AVRO,
            "table.name.format": "${topic}",
            # Same config for all tables, no per-table pk.fields:
            "pk.mode": "record_key",       # PK columns = fields of the record key
            "insert.mode": "upsert",       # inserts + updates
            "delete.enabled": "true",      # tombstone -> DELETE (needs record_key)
            "auto.create": "false",        # tables are pre-created from the same spec
            "auto.evolve": "false",
        },
    }


write("connectors/mssql-source-connector.json", json.dumps(source, indent=2) + "\n")
write("connectors/postgres-sink-connector.json",
      json.dumps(sink("postgres-sink", "jdbc:postgresql://postgres:5432/demo", "postgres", "postgres"), indent=2) + "\n")
write("connectors/db2-sink-connector.json",
      json.dumps(sink("db2-sink", "jdbc:db2://db2:50000/demo", "db2inst1", "db2inst1-pwd"), indent=2) + "\n")

# ---- Docs -------------------------------------------------------------------- #
rows = ["| # | Table | Primary key | Deletable | Notes |", "|---|-------|-------------|-----------|-------|"]
for i, t in enumerate(TABLES, 1):
    pk = ", ".join(f"`{c.name}` {c.type}" for c in t.pk)
    rows.append(f"| {i} | `{t.name}` | {pk} | {'yes' if t.deletable else 'no'} | {t.desc} |")
readme_path = os.path.join(ROOT, "README.md")
readme = open(readme_path).read()
a, b = "<!-- TABLES:START -->", "<!-- TABLES:END -->"
head, rest = readme.split(a, 1)
_, tail = rest.split(b, 1)
open(readme_path, "w").write(head + a + "\n" + "\n".join(rows) + "\n" + b + tail)
print("updated README.md tables")

write("scripts/tables.txt", "\n".join(names) + "\n")
